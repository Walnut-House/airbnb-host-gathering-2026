def chk(d, y, rows, hi=None, pad=22):
    """checklist: number + area, lines under it (core lines SemiBold)."""
    y = note(d, y - 20, "영역 · 점검할 것")
    y += 8
    s, st, lead, _ = TS["label"]
    for n, area, lines_ in rows:
        d.rect(X, y, CW, 2, LINE)
        yy = y + 2 + pad
        num_mark(d, X, yy, n, n == hi)
        yy = tx(d, X + d.ind, yy, CW - d.ind, area, "item")
        yy += 2
        for t, core in lines_:
            yy = tx(d, X + d.ind, yy + 8, CW - d.ind, t, "card", style="SemiBold" if core else "Regular")
        y = yy + pad
    d.rect(X, y, CW, 2, LINE); y += 2; d.rule_end = y
    return y

