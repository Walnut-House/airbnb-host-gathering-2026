def ck(d, y, items, hi=None, pad=22):
    """numlist with SemiBold title for core items (landscape 14-checklist)."""
    ix = X + d.ind; iw = CW - d.ind
    y, top = list_top(d, y)
    for i, (t, det, core) in enumerate(items):
        if i or top: d.rect(X, y, CW, 2, LINE)
        yy = y + 2 + pad
        num_mark(d, X, yy, i + 1, i == hi)
        yy = tx(d, ix, yy, iw, t, "item", style="SemiBold" if core else "Regular")
        yy = tx(d, ix, yy + 2, iw, det, "detail")
        y = yy + pad
    d.rect(X, y, CW, 2, LINE); y += 2; d.rule_end = y
    return y


