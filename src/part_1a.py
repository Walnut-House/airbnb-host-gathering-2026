def ranklist(d,x,y,w,items,start=1,hi=None,bold=None,pitch=64):
    for i,t in enumerate(items):
        d.rect(x,y,w,2,LINE)
        d.text(x,y+16,40,36,str(start+i),24,"SemiBold",ACC if i==hi else SEC)
        d.text(x+40,y+16,w-40,36,t,24,"SemiBold" if i in (hi,bold) else "Regular",INK)
        y+=pitch
    d.rect(x,y,w,2,LINE)
    return y

