def mlist(d,x,y,w,items,pitch,hi=None,start=1):
    """numlist variant whose detail may span several lines ('\\n')."""
    for i,(t,det) in enumerate(items):
        d.rect(x,y,w,2,LINE)
        d.text(x,y+14,40,36,str(i+start),24,"SemiBold",ACC if i==hi else SEC)
        d.text(x+40,y+14,w-40,36,t,24,"Medium",INK)
        if det:
            n=det.count("\n")+1
            d.text(x+40,y+50,w-40,int(33*n)+6,det,22,"Regular",SEC,lead=33)
        y+=pitch+33*((det.count("\n") if det else -1))
    d.rect(x,y,w,2,LINE)
    return y

def trows(d,y,rows,hi=None,lab_w=540,pad=8,first=True):
    """Label/content table on the grid (label x120, content x693). rows: (label, main, note)."""
    for i,(lab,main,nt) in enumerate(rows):
        if i or first: d.rect(120,y,W-240,2,LINE)
        d.text(120,y+20,lab_w,40,lab,26,"SemiBold",ACC if i==hi else INK)
        d.text(693,y+20,1107,40,main,24,"Regular",INK)
        h=72
        if nt:
            n=nt.count("\n")+1
            d.text(693,y+60,1107,33*n+6,nt,22,"Regular",SEC,lead=33)
            h=72+33*n
        y+=h+pad
    d.rect(120,y,W-240,2,LINE)
    return y

