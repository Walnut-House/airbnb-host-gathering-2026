def rows(d,items,y=350,hi=None,start=1,x=120,w=1680,dx=DX):
    """Full-width numbered rows: number · title (left) | detail (right, 24 INK).
    items: (title, detail) — detail lines split with \\n. Pitch 64 / 96 / 128 for 1 / 2 / 3 lines."""
    for i,(t,det) in enumerate(items):
        n=max(det.count("\n")+1, t.count("\n")+1); p=64+32*(n-1)
        d.rect(x,y,w,2,LINE)
        d.text(x,y+14,40,36,str(start+i),24,"SemiBold",ACC if i==hi else SEC)
        tn=t.count("\n")+1
        d.text(x+40,y+14,dx-x-40-24,36*tn+4,t,24,"SemiBold",INK,lead=36)
        d.text(dx,y+14,x+w-dx,36*n+4,det,24,"Regular",INK,lead=36)
        y+=p
    d.rect(x,y,w,2,LINE)
    return y

def plist(d,x,y,w,items,pitch=64,hi=None,labels=None):
    """numlist variant with custom number labels (e.g. '7~8')."""
    for i,t in enumerate(items):
        d.rect(x,y,w,2,LINE)
        lab=labels[i] if labels else str(i+1)
        d.text(x,y+14,60,36,lab,24,"SemiBold",ACC if i==hi else SEC)
        d.text(x+(64 if labels else 40),y+14,w-64,36,t,24,"Regular",INK)
        y+=pitch
    d.rect(x,y,w,2,LINE); return y

