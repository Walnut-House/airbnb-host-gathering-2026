def trows(d, rows, y=396, mid=300, txt=693, red=None, label_w=None, lh=34):
    """Table body like slide 24: label (26 SemiBold) | optional amount (28 Bold) + note | text lines (24).
    rows: (label, amount, amount_note, text_with_newlines). red = row index whose amount (or label) is red."""
    for i, (k, amt, an, v) in enumerate(rows):
        n = v.count("\n") + 1
        if i: d.rect(L, y, FW, 2, LINE)
        lab_red = (i == red and not amt)
        d.text(L, y+20, label_w or (mid-L-20 if mid else txt-L-40), 40, k, 26, "SemiBold", ACC if lab_red else INK)
        if amt:
            d.text(mid, y+16, txt-mid-20, 40, amt, 28, "Bold", ACC if i == red else INK)
            if an: note(d, mid, y+60, txt-mid-20, an, lines=an.count("\n")+1)
        d.text(txt, y+20, W-120-txt, lh*n+8, v, 24, "Regular", INK, lead=(lh if lh != 34 else None))
        h = lh*n + 36
        if an: h = max(h, 60 + 34*(an.count("\n")+1) + 20)
        y += h
    d.rect(L, y, FW, 2, LINE)
    return y


