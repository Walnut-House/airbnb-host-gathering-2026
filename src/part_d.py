def wraplist(d, x, y, w, items, pitch=96, hi=None, size=24):
    """numlist style, but each row's text may wrap to 2 lines at column width."""
    for i, t in enumerate(items):
        d.rect(x, y, w, 2, LINE)
        d.text(x, y+14, 40, size*1.5, str(i+1), size, "SemiBold", ACC if i == hi else SEC)
        d.text(x+40, y+14, w-40, size*3+4, t, size, "Regular", INK)
        y += pitch
    d.rect(x, y, w, 2, LINE)
    return y

